import type { ITimeframeStats } from "../lib/models.js";

type Quest = {
	name: string;
	description: string;
	isCompleted: (stats: ITimeframeStats) => boolean;
	getCompletion: (stats: ITimeframeStats) => number;
	reward: {
		coins?: number;
		horse?: string;
	};
	difficulty: "easy" | "medium" | "hard";
	category:
		| "gambling"
		| "spawns"
		| "begs"
		| "donations"
		| "races"
		| "leaderboard"
		| "trade";
	guaranteed?: boolean;
};

// eslint-disable-next-line max-params -- threshold definitions keep their metadata explicit
function thresholdQuest(
	name: string,
	description: string,
	difficulty: Quest["difficulty"],
	category: Quest["category"],
	getValue: (stats: ITimeframeStats) => number,
	target: number,
	reward: Quest["reward"] = difficulty === "easy"
		? { coins: 4 }
		: difficulty === "medium"
			? { horse: "gildedness_stratification", coins: 6 }
			: { horse: "brightness_prosperity", coins: 10 },
): Quest {
	return {
		name,
		description,
		isCompleted: (stats) => getValue(stats) >= target,
		getCompletion: (stats) =>
			Math.min(1, getValue(stats) / target),
		reward,
		difficulty,
		category,
	};
}

